#!/usr/bin/env python3
"""Release Builder v1.8 — package staging/curated artifacts into a versioned bundle.

Creates an immutable-style release bundle under ``metadata/release_bundles/<version>/``:
  - canonical dataset snapshot (JSONL)
  - training views (copied/referenced)
  - evaluation holdout
  - file-level checksum manifest
  - dataset card
  - release notes

Does NOT publish to HuggingFace Hub by default (optional stub).
Does NOT write to curated/ — promotion into curated/ remains a human-gated step.
"""

from __future__ import annotations

import hashlib
import json
import shutil
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Any

from etl.types import read_jsonl, utc_now, write_jsonl


@dataclass
class ReleaseBuildResult:
    version: str
    status: str
    summary: str
    bundle_dir: str = ""
    files: list[dict[str, Any]] = field(default_factory=list)
    record_count: int = 0
    errors: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


def _sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _copy_file(src: Path, dest: Path) -> dict[str, Any]:
    dest.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(src, dest)
    return {
        "path": str(dest),
        "relative": dest.name,
        "bytes": dest.stat().st_size,
        "sha256": _sha256_file(dest),
        "source": str(src),
    }


def _render_dataset_card(
    *,
    version: str,
    record_count: int,
    models: list[str],
    source_ids: list[str],
    license_summary: dict[str, int],
    mode: str,
) -> str:
    licenses = ", ".join(f"{k} ({v})" for k, v in sorted(license_summary.items())) or "unknown"
    return f"""# Atlas Dataset {version}

> Auto-generated by Release Builder v1.8. Mode: **{mode}**.

## Overview

Versioned release bundle produced from the Atlas ETL → Transform → Views pipeline.

| Metric | Value |
|---|---|
| Version | {version} |
| Records | {record_count} |
| Sources | {', '.join(source_ids) or 'n/a'} |
| Training views | {', '.join(models) or 'n/a'} |
| Licenses | {licenses} |
| Verified | staging bundles are **unverified** until human review |

## Contents

- `data/canonical.jsonl` — canonical Atlas records in this bundle
- `views/<model>/train.jsonl` — model-family training views
- `eval/holdout.jsonl` — deterministic held-out evaluation split
- `manifest.json` — file-level SHA-256 checksums
- `RELEASE_NOTES.md` — human-readable notes

## Provenance

Records carry per-item `lineage` and `source` fields. Do not treat staging
bundles as production curated releases.

## License

Per-record licenses apply. Aggregate distribution may require satisfying the
strictest share-alike / attribution obligations present in the mix.
"""


def _render_release_notes(
    *,
    version: str,
    record_count: int,
    type_counts: dict[str, int],
    models: list[str],
    source_ids: list[str],
    mode: str,
) -> str:
    types = "\n".join(f"- `{k}`: {v}" for k, v in sorted(type_counts.items())) or "- (none)"
    return f"""# Release Notes — {version}

Generated: {utc_now()}
Mode: {mode}

## Summary

Bundled **{record_count}** Atlas records from sources: {', '.join(source_ids) or 'n/a'}.

## Training types

{types}

## Views generated

{', '.join(models) or '(none)'}

## Gate reminder

This Release Builder packages artifacts only. Promotion into ``curated/`` and
official ``RELEASED`` pipeline state still require the Automation Layer human
approval gate.
"""


def build_release(
    root: str | Path,
    *,
    version: str,
    source_ids: list[str] | None = None,
    view_version: str | None = None,
    allow_staging: bool = True,
    hub_publish: bool = False,
) -> ReleaseBuildResult:
    root = Path(root).resolve()
    view_version = view_version or version
    source_ids = source_ids or []

    views_dir = root / "metadata" / "views" / view_version
    bundle_dir = root / "metadata" / "release_bundles" / version
    bundle_dir.mkdir(parents=True, exist_ok=True)

    result = ReleaseBuildResult(
        version=version,
        status="passed",
        summary="",
        bundle_dir=str(bundle_dir),
    )

    # Collect canonical records — prefer the views snapshot when present so
    # release contents match the train split that views were built from.
    records: list[dict[str, Any]] = []
    views_snap = views_dir / "canonical_train.jsonl"
    if views_snap.exists():
        records = read_jsonl(views_snap)
        eval_snap = views_dir / "eval_holdout.jsonl"
        if eval_snap.exists():
            records = records + read_jsonl(eval_snap)
        if not source_ids:
            source_ids = ["(from-views)"]
    elif not source_ids:
        etl_root = root / "metadata" / "etl"
        if etl_root.exists():
            source_ids = sorted(p.name for p in etl_root.iterdir() if p.is_dir())
        for sid in source_ids:
            etl_dir = root / "metadata" / "etl" / sid
            for name in ("transformed_atlas.jsonl", "atlas_staging.jsonl"):
                path = etl_dir / name
                if path.exists():
                    records.extend(read_jsonl(path))
                    break
    else:
        for sid in source_ids:
            etl_dir = root / "metadata" / "etl" / sid
            for name in ("transformed_atlas.jsonl", "atlas_staging.jsonl"):
                path = etl_dir / name
                if path.exists():
                    records.extend(read_jsonl(path))
                    break

    if not records:
        result.status = "failed"
        result.errors.append("no records available to bundle — run transform/views first")
        result.summary = "Release build failed: no records"
        return result

    if not allow_staging:
        approved = [
            r for r in records
            if r.get("verified") is True or r.get("verification_status") == "approved"
        ]
        if not approved:
            result.status = "blocked"
            result.errors.append("BLOCKED: production release requires approved records")
            result.summary = "Release build blocked"
            return result
        records = approved

    result.record_count = len(records)
    mode = "staging" if allow_staging else "production"

    # Write canonical data
    data_dir = bundle_dir / "data"
    data_dir.mkdir(exist_ok=True)
    canonical_path = data_dir / "canonical.jsonl"
    write_jsonl(canonical_path, records)
    files = [
        {
            "path": str(canonical_path.relative_to(bundle_dir)),
            "bytes": canonical_path.stat().st_size,
            "sha256": _sha256_file(canonical_path),
            "role": "canonical",
        }
    ]

    # Copy views if present
    models: list[str] = []
    if views_dir.exists():
        for model_dir in sorted(p for p in views_dir.iterdir() if p.is_dir()):
            train = model_dir / "train.jsonl"
            if not train.exists():
                continue
            dest = bundle_dir / "views" / model_dir.name / "train.jsonl"
            info = _copy_file(train, dest)
            files.append(
                {
                    "path": str(dest.relative_to(bundle_dir)),
                    "bytes": info["bytes"],
                    "sha256": info["sha256"],
                    "role": f"view:{model_dir.name}",
                }
            )
            models.append(model_dir.name)

        eval_src = views_dir / "eval_holdout.jsonl"
        if eval_src.exists():
            dest = bundle_dir / "eval" / "holdout.jsonl"
            info = _copy_file(eval_src, dest)
            files.append(
                {
                    "path": str(dest.relative_to(bundle_dir)),
                    "bytes": info["bytes"],
                    "sha256": info["sha256"],
                    "role": "eval_holdout",
                }
            )
    else:
        result.warnings.append(f"views not found at {views_dir}; bundle has canonical only")

    # Stats for card / notes
    license_summary: dict[str, int] = {}
    type_counts: dict[str, int] = {}
    for rec in records:
        lic = (rec.get("source") or {}).get("license") if isinstance(rec.get("source"), dict) else "unknown"
        license_summary[str(lic)] = license_summary.get(str(lic), 0) + 1
        t = rec.get("training_type") or rec.get("type") or "unknown"
        type_counts[str(t)] = type_counts.get(str(t), 0) + 1

    card = _render_dataset_card(
        version=version,
        record_count=len(records),
        models=models,
        source_ids=[s for s in source_ids if s != "(from-views)"],
        license_summary=license_summary,
        mode=mode,
    )
    card_path = bundle_dir / "README.md"
    card_path.write_text(card, encoding="utf-8")
    files.append(
        {
            "path": "README.md",
            "bytes": card_path.stat().st_size,
            "sha256": _sha256_file(card_path),
            "role": "dataset_card",
        }
    )

    notes = _render_release_notes(
        version=version,
        record_count=len(records),
        type_counts=type_counts,
        models=models,
        source_ids=[s for s in source_ids if s != "(from-views)"],
        mode=mode,
    )
    notes_path = bundle_dir / "RELEASE_NOTES.md"
    notes_path.write_text(notes, encoding="utf-8")
    files.append(
        {
            "path": "RELEASE_NOTES.md",
            "bytes": notes_path.stat().st_size,
            "sha256": _sha256_file(notes_path),
            "role": "release_notes",
        }
    )

    manifest = {
        "version": version,
        "generated_at": utc_now(),
        "mode": mode,
        "record_count": len(records),
        "models": models,
        "source_ids": source_ids,
        "files": files,
        "bundle_checksum": hashlib.sha256(
            json.dumps(files, sort_keys=True).encode()
        ).hexdigest(),
        "hub_publish": False,
    }
    if hub_publish:
        result.warnings.append(
            "HuggingFace Hub publish requested but not executed "
            "(optional stub — configure credentials / enable in a future pass)"
        )
        manifest["hub_publish"] = "skipped_not_configured"

    manifest_path = bundle_dir / "manifest.json"
    manifest_path.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    # Recompute files list including manifest itself
    files.append(
        {
            "path": "manifest.json",
            "bytes": manifest_path.stat().st_size,
            "sha256": _sha256_file(manifest_path),
            "role": "manifest",
        }
    )

    result.files = files
    result.summary = (
        f"Release bundle {version}: {len(records)} records, "
        f"{len(models)} view(s), {len(files)} files → {bundle_dir}"
    )
    return result
